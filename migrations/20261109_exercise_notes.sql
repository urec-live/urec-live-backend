ALTER TABLE exercise ADD COLUMN IF NOT EXISTS secondary_muscles VARCHAR(500);

-- Private, per-member pinned notes. Deploy before the exercise-detail client.
CREATE TABLE IF NOT EXISTS exercise_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    exercise_id BIGINT NOT NULL REFERENCES exercise(id) ON DELETE CASCADE,
    note VARCHAR(2000) NOT NULL DEFAULT '',
    CONSTRAINT uk_exercise_notes_user_exercise UNIQUE (user_id, exercise_id)
);
-- Rollback after reverting the client/backend: DROP TABLE exercise_notes;
-- Dropping this table permanently discards pinned notes.
